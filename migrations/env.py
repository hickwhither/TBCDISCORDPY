import asyncio
import os
import pathlib
from logging.config import fileConfig

from dotenv import load_dotenv
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from alembic import context

load_dotenv()

# this is the Alembic Config object, which provides
# access to the values within the .ini file in use.
config = context.config

# Make the URL come from DATABASE_URL (same default as core.database).
DATABASE_URL = os.environ.get("DATABASE_URL", "sqlite+aiosqlite:///data/tbc.db")
config.set_main_option("sqlalchemy.url", DATABASE_URL)

# Ensure the SQLite directory exists before the engine connects.
if DATABASE_URL.startswith("sqlite"):
    db_path = DATABASE_URL.rsplit("///", 1)[-1]
    if db_path and db_path != "memory":
        parent = os.path.dirname(db_path) or "."
        pathlib.Path(parent).mkdir(parents=True, exist_ok=True)

# Interpret the config file for Python logging.
# This line sets up loggers basically.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Add your model's MetaData object here
# for 'autogenerate' support.
from core.database import Base  # noqa: E402

import features.antiraid.models  # noqa: E402, F401
import features.connhen.models  # noqa: E402, F401

target_metadata = Base.metadata

# other values from the config, defined by the needs of env.py,
